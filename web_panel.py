"""Lightweight local web panel for the Feishu research assistant.

Provides a dashboard (request volume, success rate, latency, token usage,
tool ranking), a filterable request log with detail views, and a runtime
status page. Follows the pattern of LangBot / Dify monitoring pages: summary
cards, list + lazy detail, JSON API.

Run standalone:  python web_panel.py        (default http://127.0.0.1:8090)
Optional auth:   set PANEL_TOKEN to require a token (?token=... or header).
"""

